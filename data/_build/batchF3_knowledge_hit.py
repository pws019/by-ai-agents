OPENERS = ["您好，理解您的疑问，", "您好，收到您的问题了，", "您好，感谢您的耐心，", "您好，很高兴为您解答，"]


def repair_item(i, source, title, user_msg, cause, step):
    score = round(0.82 - (i % 5) * 0.01, 2)
    chunk = {
        "text": f"**可能原因**：{cause}。\n**排查与维修步骤**：{step}。",
        "source": source,
        "title": title,
        "chunkIndex": i % 4,
        "score": score,
    }
    obs = {"relevantContext": [chunk], "sources": [chunk]}
    answer = (
        f"{OPENERS[i % len(OPENERS)]}根据资料，这种情况常见原因是{cause}。"
        f"建议您先{step}；如果按步骤处理后仍没有解决，建议联系专业维修人员或申请转人工进一步协助。"
    )
    return mk_tool_call(user_msg, "knowledgeRagTool", {"queryText": user_msg, "topK": 25}, obs, answer)


def general_item(i, topic, user_msg, fact):
    score = round(0.78 - (i % 5) * 0.01, 2)
    chunk = {
        "text": fact,
        "source": f"{topic}知识库",
        "title": topic,
        "chunkIndex": i % 3,
        "score": score,
    }
    obs = {"relevantContext": [chunk], "sources": [chunk]}
    answer = f"{OPENERS[i % len(OPENERS)]}{fact}如果还有其他细节需要确认，欢迎随时告诉我。"
    return mk_tool_call(user_msg, "knowledgeRagTool", {"queryText": user_msg, "topK": 25}, obs, answer)


